make_admin1_profiles <- function(evidence, idmc_detail, isos, out) {
  ## Subnational layer. ACLED aggregated already carries ADMIN1; IDMC IDU rows
  ## carry coordinates plus a Locations accuracy field indicating ADM1/2/3.
  a <- evidence |>
    filter(iso3 %in% isos, !is.na(admin1), evidence_type == "events") |>
    group_by(iso3, admin1, code_id) |>
    summarise(events = sum(value), .groups = "drop") |>
    group_by(iso3, admin1) |> mutate(share = events / sum(events)) |> ungroup()
  if (!nrow(a)) {
    message("no admin1 evidence for the requested countries - ",
            "add the ACLED regional exports that cover them")
    return(invisible(NULL))
  }
  readr::write_csv(a, file.path(out, "admin1_cause_profiles.csv"))
  message("admin1 profiles: ", nrow(a), " rows -> admin1_cause_profiles.csv")
  invisible(a)
}
